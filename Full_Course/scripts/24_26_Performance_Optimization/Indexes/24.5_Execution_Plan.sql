-- The GOLDEN RULE: AVOID OVER INDEXING (= LESS is MORE)
--	1. Slows performance
--	2. Confuse Execution Plan (=slows performance)
--	3. Less but more effective INDEXES leads to better performance


-- INDEXES SLOWS DOWN WRTIE PERFORMANCE:
--	When data is inserted, updated or deleted, database has to update indexes

-- Too many INDEXES can confuse Execution Plan:
--	Increase plannint time
--	Choose a suboptimal plan


-- <<<<< #1 Initial Strategy (20:55:25) >>>>>
-- WHat is the MAIN goal of our INDEXING strategy?

-- Mainly 2 types of Databases:

-- OLAP (Online Analytical Processing): 
-- Purpose: BI-, Data-, Report Analitics
-- Use: DWH (Data Warehouse) 
-- Going to be HEAVY READING on this type of DB
-- GOAL: Optimize READ Performance for Data Analytical tools
-- Best type of INDEX: COLUMNSTORE INDEX

-- OLTP (Online Transaction Processing):
-- Purpose: Ecommerce, finance, banking
-- Going to be HEAVY WRITING and READING on this type of DB
-- GOAL: Optimize WRITE (and READ) Performance for Applications
-- Best type of INDEX: CLUSTERED INDEX for each Primary Key

-- What do you want to achieve?
-- Optimize READ Performance
-- Optimize WRITE Performance



