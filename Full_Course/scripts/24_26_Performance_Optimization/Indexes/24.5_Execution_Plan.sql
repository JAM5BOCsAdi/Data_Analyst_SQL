	p.EnglishProductName AS ProductName,
	SUM(s.SalesAmount) AS TotalSales
FROM FactResellerSales_HP AS s
INNER JOIN DimProduct AS p
	ON p.ProductKey = s.ProductKey
GROUP BY p.EnglishProductName;
GO

